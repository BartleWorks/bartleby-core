"""Regenerate bartleby/shared/data/deck_names.json from the game's Root.wad.

Run this when a game patch adds a world or a kind to the rename window's wheels, or rewords
one in any locale. Everything else reads the checked-in snapshot, so neither the app nor its
tests need the game installed.

WHAT IT READS
    Locale/<loc>/DeckNames.lang: the choices of the three wheels a deck's name is picked from
    (``Class_N``, ``Type_N``, ``Num_N``), ``DeckName``, which composes a name of them, and
    ``None``, the wheels' word for an empty choice:

        Class_7   -> "Storm "
        Type_2    -> "Boss "
        Num_1     -> "1"
        DeckName  -> "$PART0$$PART1$Deck $PART2$"
        None      -> "(None)"

    The text is kept as the game has it, spaces and markup included: bartleby.shared.deck_names
    composes it. A wheel's empty choice (``Class_0``) is blank in every locale and is left out.

WHY PER LOCALE
    The wheels differ: en-US has Class_36 (Ahmarra), which de does not yet. So the snapshot
    holds each locale's own table, and a locale is never filled in from another.

WHY A SNAPSHOT IS SAFE
    A wheel's choice is looked up by its own key, which is what a deck's memory holds, so a
    stale snapshot cannot misname a deck. It can only lack a choice the game has just added.

USAGE
    uv run python tools/dump_deck_names.py
    uv run python tools/dump_deck_names.py --wad "D:/Games/Wizard101/Data/GameData/Root.wad"
    uv run python tools/dump_deck_names.py --verify      # no write; check the current file

    --verify also compares the file with the Root.wad, where the game is installed.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from datetime import date
from pathlib import Path

from katsuba.wad import Archive

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from bartleby.shared.deck_names import COMPOSED_BY, DECK_NAMES_PATH, EMPTY_CHOICE, Wheel  # noqa: E402
from bartleby.shared.locales import DEFAULT_LOCALE, LOCALES  # noqa: E402

# Deck names include Greek, which a cp1252 console cannot encode. Without this the tool dies
# on its own progress output.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_WAD = Path(r"C:\ProgramData\KingsIsle Entertainment\Wizard101\Data\GameData\Root.wad")

LANG_FILE = "DeckNames"


def parse_lang(raw: bytes) -> dict[str, str]:
    """Parse a .lang file into {key: display text}.

    UTF-16LE with CRLF endings, a one-line header, then fixed three-line records of
    key / translator description / display text. Slice at a fixed stride rather than
    walking: the description is usually but not always blank.
    """
    lines = raw.decode("utf-16-le", errors="replace").lstrip("\ufeff").split("\r\n")
    return {lines[i]: lines[i + 2] for i in range(1, len(lines) - 2, 3) if lines[i]}


def wheel_key(key: str) -> tuple[Wheel, int] | None:
    """The wheel and choice *key* names, or None for a key of another kind."""
    for wheel in Wheel:
        try:
            return wheel, wheel.index(key)
        except ValueError:
            continue
    return None


def deck_name_table(lang: Mapping[str, str]) -> dict[str, str]:
    """One locale's DeckNames.lang as the snapshot holds it: the composer, the empty choice, the wheels in order.

    A choice with no text is left out: each wheel's empty one, and any the game has retired.
    """
    table = {key: lang[key] for key in (COMPOSED_BY, EMPTY_CHOICE) if lang.get(key)}
    order = {wheel: place for place, wheel in enumerate(Wheel)}
    keys = [(order[found[0]], found[1], key) for key in lang if (found := wheel_key(key))]
    return table | {key: lang[key] for _, _, key in sorted(keys) if lang[key].strip()}


def build_snapshot(archive: Mapping[str, bytes], source: Path) -> dict:
    """The snapshot of *archive*, a Root.wad. A locale with no DeckNames.lang is reported and left out."""
    tables: dict[str, dict[str, str]] = {}
    for locale in LOCALES:
        path = f"Locale/{locale}/{LANG_FILE}.lang"
        try:
            raw = archive[path]
        except KeyError:
            print(f"  !! {path}: not in the archive")
            continue
        tables[locale] = deck_name_table(parse_lang(raw))
    return {
        "_comment": (
            "Generated by tools/dump_deck_names.py -- do not hand-edit. "
            "See bartleby/shared/deck_names.py for how these are used."
        ),
        "generated": date.today().isoformat(),
        "source": str(source),
        "locales": tables,
    }


def verify(snapshot: dict) -> list[str]:
    """What the snapshot cannot answer, one line each. Empty when it is whole.

    A key only some locales hold is not a problem: the wheels differ per locale.
    """
    tables: dict[str, dict[str, str]] = snapshot.get("locales", {})
    problems = [f"{locale}: no table" for locale in LOCALES if not tables.get(locale)]
    english = tables.get(DEFAULT_LOCALE, {})
    for locale, table in tables.items():
        composer = table.get(COMPOSED_BY, "")
        missing = [f"$PART{i}$" for i in range(len(Wheel)) if f"$PART{i}$" not in composer]
        if missing:
            problems.append(f"{locale}: {COMPOSED_BY} {composer!r} lacks {', '.join(missing)}")
        if not table.get(EMPTY_CHOICE):
            problems.append(f"{locale}: no text for the empty choice")
        for wheel in Wheel:
            if not any(key.startswith(f"{wheel}_") for key in table):
                problems.append(f"{locale}: the {wheel} wheel is empty")
        for key, text in table.items():
            if key in (COMPOSED_BY, EMPTY_CHOICE):
                continue
            if wheel_key(key) is None:
                problems.append(f"{locale}: {key!r} is on no wheel")
            elif not text.strip():
                problems.append(f"{locale}: {key} has no text")
            elif key not in english:
                # A name with this key would show it raw in every other locale.
                problems.append(f"{locale}: {key} is not in {DEFAULT_LOCALE}")
    return problems


def differences(snapshot: dict, fresh: dict) -> list[str]:
    """Where *snapshot*'s tables and *fresh*'s differ, one line each."""
    lines = []
    old, new = snapshot.get("locales", {}), fresh.get("locales", {})
    for locale in LOCALES:
        was, now = old.get(locale, {}), new.get(locale, {})
        for key in sorted(was.keys() | now.keys()):
            if was.get(key) != now.get(key):
                lines.append(f"{locale}: {key} is {was.get(key)!r} here and {now.get(key)!r} in the game")
    return lines


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wad", type=Path, default=DEFAULT_WAD, help="path to Root.wad")
    ap.add_argument("--out", type=Path, default=DECK_NAMES_PATH, help="where to write the snapshot")
    ap.add_argument("--verify", action="store_true", help="check the existing snapshot; do not write")
    args = ap.parse_args()

    if args.verify:
        if not args.out.exists():
            print(f"no snapshot at {args.out}")
            return 1
        snapshot = json.loads(args.out.read_text(encoding="utf-8"))
        print(f"verifying {args.out}")
        problems = verify(snapshot)
        if args.wad.exists():
            print(f"against {args.wad}")
            problems += differences(snapshot, build_snapshot(Archive.mmap(str(args.wad)), args.wad))
        else:
            print(f"Root.wad not found at {args.wad}: the file alone was checked")
        for problem in problems:
            print(f"  !! {problem}")
        print("problems found" if problems else "ok")
        return 1 if problems else 0

    if not args.wad.exists():
        print(f"Root.wad not found at {args.wad}; pass --wad")
        return 1

    snapshot = build_snapshot(Archive.mmap(str(args.wad)), args.wad)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(snapshot, indent=1, ensure_ascii=False), encoding="utf-8")

    print(f"wrote {args.out}")
    for locale, table in snapshot["locales"].items():
        sizes = ", ".join(f"{sum(key.startswith(f'{wheel}_') for key in table)} {wheel}" for wheel in Wheel)
        print(f"  {locale:<6} {sizes}")
    problems = verify(snapshot)
    for problem in problems:
        print(f"  !! {problem}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
